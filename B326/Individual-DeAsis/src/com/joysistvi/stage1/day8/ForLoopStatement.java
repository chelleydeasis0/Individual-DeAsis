package com.joysistvi.stage1.day8;

public class ForLoopStatement {

    public static void main(String[] args) {

        //Syntax For Loops

        for (int i = 0; i <= 10; i++) {
            System.out.print(i + " ");
        }

        // print number from 5-20

        for (int i = 5; i <= 20; i++ ) {
            System.out.println(i);
        }

        for (int i = 1; i <= 20; i++) {
            System.out.println(i + " ");
        }

    }
}
