package com.joysistvi.stage1.day8;

public class DoWhileStatement {

    public static void main(String[] args) {

        /*
            initialization;
            do {
                statement / body of the loop
                increment / decrement
            } while (condition);
         */

        int i = 1;
        do {
            System.out.println(1);
            i++;
        } while (i <= 10);




    }
}
