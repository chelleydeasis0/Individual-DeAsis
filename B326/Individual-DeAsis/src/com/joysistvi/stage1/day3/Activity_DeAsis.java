package com.joysistvi.stage1.day3;

public class Activity_DeAsis {

    public static void main(String[] args) {

        //Boolean
        boolean isActive = true;
        System.out.println("Boolean value: " + isActive);

        // Byte
        byte smallNumber = 100;
        System.out.println("Byte value: " + smallNumber);

        //Short
        short shortNumber = 20000;
        System.out.println("Short value: " + shortNumber);

        //Int
        int age = 25;
        System.out.println("Int value: " + age);

        //Long
        long population = 7800000000L;
        System.out.println("Long value: " + population);

        //Float
        float temperature = 36.7f;
        System.out.println("Float value: " + temperature);

        //Double
        double pi = 3.14159;
        System.out.println("Double value: " + pi);

        //Char
        char grade = 'A';
        System.out.println("Char value: " + grade);

        String fullname = " Rechelle De Asis";
        System.out.println("Fullname value: " + fullname);

    }
}
