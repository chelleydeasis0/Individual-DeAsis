package com.joysistvi.stage1.day12;

public class Activity11_MathClass_DeAsis {

    public static void main(String[] args) {

        // Example of Math.abs()
        System.out.println(Math.abs(-10)); // 10

        // Example of Math.max()
        System.out.println(Math.max(5, 9)); // 9

        // Example of Math.min()
        System.out.println(Math.min(5, 9)); // 5

        // Example of Math.pow()
        System.out.println(Math.pow(2, 3)); // 8.0

        // Example of Math.sqrt()
        System.out.println(Math.sqrt(16)); // 4.0

        // Example of Math.round()
        System.out.println(Math.round(4.6)); // 5

        // Example of Math.ceil()
        System.out.println(Math.ceil(4.2)); // 5.0

        // Example of Math.floor()
        System.out.println(Math.floor(4.9)); // 4.0

        // Example of Math.random()
        System.out.println(Math.random()); // e.g. 0.345

        // Example of Math.log()
        System.out.println(Math.log(10)); // ~2.302

        // Example of Math.log10()
        System.out.println(Math.log10(100)); // 2.0

        // Example of Math.exp()
        System.out.println(Math.exp(2)); // ~7.389

        // Example of Math.sin()
        System.out.println(Math.sin(Math.PI / 2)); // 1.0

        // Example of Math.cos()
        System.out.println(Math.cos(0)); // 1.0

        // Example of Math.tan()
        System.out.println(Math.tan(Math.PI / 4)); // 1.0

    }

}